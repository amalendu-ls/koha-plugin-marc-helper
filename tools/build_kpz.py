"""Build the Koha plugin package: python tools/build_kpz.py [output folder]

The panel reuses the browser extension's code (one source of truth). When the extension
folder is next to this one (../KohaMARCHelper), its shared files are first copied into
Koha/Plugin/MarcHelper/static/ (marc-*.js as they are; background.js and content.js wrapped
as engine.js and filler.js); these copies are kept in the repository, so the plugin also
builds on its own (a fresh clone, the release job). Then staticapi.json is written (Koha
serves only the static files listed there), the JavaScript and JSON are checked, and Koha/
and LICENSE are packed into koha-plugin-marchelper-v<version>.kpz (default: Downloads).
Koha MARC Helper, GPL v3 or later.
"""
import json
import os
import re
import shutil
import subprocess
import sys
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXTENSION = os.path.join(os.path.dirname(ROOT), 'KohaMARCHelper')
PLUGIN_DIR = os.path.join('Koha', 'Plugin', 'MarcHelper')
SHARED = {  # extension file -> static file name (page scripts, used as they are)
    'lib/marc-parser.js': 'marc-parser.js',
    'lib/marcxml.js': 'marcxml.js',
    'lib/marc-tools.js': 'marc-tools.js',
    'lib/marc-labels.js': 'marc-labels.js',
}
# Extension scripts that expect the browser-extension API: each is wrapped in a function
# that receives stand-ins (chrome, fetch) from the panel and returns the functions it needs.
# No eval, so the panel also works where Koha sends a Content-Security-Policy.
WRAPPED = {  # extension file -> (static file name, name on window.MarcHelperShared, functions)
    'background.js': ('engine.js', 'engine', ['searchBooks', 'makeRecord', 'sourceNames', 'lcshCheck', 'handleAiHelper']),
    'content/content.js': ('filler.js', 'filler', ['populateFields', 'getTagBlocks', 'findSubfieldInput']),
}

WRAPPER = '''/* Generated by tools/build_kpz.py from the Koha MARC Helper extension's %(src)s.
   GPL v3 or later, see LICENSE. */
window.MarcHelperShared = window.MarcHelperShared || {};
window.MarcHelperShared.%(name)s = function (chrome, fetch, importScripts) {
%(code)s
;return {%(exports)s};
};
'''
TYPES = {'.js': 'application/javascript', '.css': 'text/css'}


def static_spec(files):
    error = {'type': 'object', 'properties': {'error': {'type': 'string'}}}
    spec = {}
    for name in files:
        spec['/static/' + name] = {'get': {
            'x-mojo-to': 'Static#get',
            'tags': ['pluginStatic'],
            # ?v=<plugin version> makes browsers fetch new files after an upgrade; Koha's API
            # refuses query parameters a route does not declare, so it is declared here
            'parameters': [{'name': 'v', 'in': 'query', 'required': False, 'type': 'string',
                            'description': 'Plugin version, so upgrades are not served from the browser cache'}],
            'produces': [TYPES.get(os.path.splitext(name)[1], 'application/octet-stream')],
            'responses': {
                '200': {'description': 'File found', 'schema': {'type': 'file'}},
                '400': {'description': 'Bad request', 'schema': error},
                '404': {'description': 'File not found', 'schema': error},
                '500': {'description': 'Internal server error', 'schema': error},
            },
        }}
    return spec


def version():
    text = open(os.path.join(ROOT, 'Koha', 'Plugin', 'MarcHelper.pm'), encoding='utf-8').read()
    return re.search(r"our \$VERSION\s*=\s*'([^']+)'", text).group(1)


def sync_from_extension():
    """Copy the extension's shared code into the plugin's static folder (kept in the repository)."""
    static = os.path.join(ROOT, PLUGIN_DIR, 'static')
    for src, name in SHARED.items():
        code = open(os.path.join(EXTENSION, src), encoding='utf-8').read()
        with open(os.path.join(static, name), 'w', encoding='utf-8', newline='\n') as f:
            f.write(code)
    for src, (name, key, exports) in WRAPPED.items():
        code = open(os.path.join(EXTENSION, src), encoding='utf-8').read()
        with open(os.path.join(static, name), 'w', encoding='utf-8', newline='\n') as f:
            f.write(WRAPPER % {'src': src, 'name': key, 'code': code, 'exports': ', '.join(exports)})


def main():
    out_dir = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.expanduser('~'), 'Downloads')
    os.makedirs(out_dir, exist_ok=True)
    if os.path.isdir(EXTENSION):
        sync_from_extension()
        print('Shared code copied from %s' % EXTENSION)
    else:
        print('Extension folder not found: building from the shared code kept in the repository')
    static_src = os.path.join(ROOT, PLUGIN_DIR, 'static')
    missing = [name for name in list(SHARED.values()) + [v[0] for v in WRAPPED.values()]
               if not os.path.isfile(os.path.join(static_src, name))]
    if missing:
        sys.exit('Missing shared files: %s (build once next to the extension folder)' % ', '.join(missing))
    # staticapi.json lists every static file (kept in the repository too)
    files = sorted(os.listdir(static_src))
    with open(os.path.join(ROOT, PLUGIN_DIR, 'staticapi.json'), 'w', encoding='utf-8', newline='\n') as f:
        json.dump(static_spec(files), f, indent=1)
        f.write('\n')

    build = os.path.join(ROOT, 'build')
    shutil.rmtree(build, ignore_errors=True)
    shutil.copytree(os.path.join(ROOT, 'Koha'), os.path.join(build, 'Koha'))
    static = os.path.join(build, PLUGIN_DIR, 'static')
    shutil.copyfile(os.path.join(ROOT, 'LICENSE'), os.path.join(build, 'LICENSE'))

    # JavaScript syntax (node) – Perl is checked on the Koha server, where Koha's modules are
    for name in files:
        if name.endswith('.js'):
            subprocess.run(['node', '--check', os.path.join(static, name)], check=True)
    for path in ('openapi.json', 'staticapi.json'):
        json.load(open(os.path.join(build, PLUGIN_DIR, path), encoding='utf-8'))

    out = os.path.join(out_dir, 'koha-plugin-marchelper-v%s.kpz' % version())
    with zipfile.ZipFile(out, 'w', zipfile.ZIP_DEFLATED) as z:
        for folder, _, names in os.walk(build):
            for name in sorted(names):
                full = os.path.join(folder, name)
                z.write(full, os.path.relpath(full, build).replace(os.sep, '/'))
    print('%s: %d files, %d bytes' % (out, len(zipfile.ZipFile(out).namelist()), os.path.getsize(out)))


if __name__ == '__main__':
    main()
